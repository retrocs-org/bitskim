#!/usr/bin/env python3
"""Generate client palette tables from one committed source."""
from pathlib import Path
import json
ROOT=Path(__file__).resolve().parents[1]
themes=json.loads((ROOT/'assets/themes/palettes.json').read_text())
roles=('base','surface','text','muted','accent','shine','shadow')
assert len({t['id'] for t in themes})==len(themes)
for t in themes:
    for r in roles: assert len(t[r])==6 and 0<=int(t[r],16)<=0xffffff
swift='// Generated by scripts/generate-themes.py; edit assets/themes/palettes.json.\nimport SwiftUI\nimport AppKit\n\n'
swift+='''struct AppTheme: Identifiable {
    let id: String, name: String
    let dark: Bool
    let baseHex: UInt32, surfaceHex: UInt32, textHex: UInt32, mutedHex: UInt32, accentHex: UInt32
    static func ns(_ hex: UInt32) -> NSColor { NSColor(srgbRed: CGFloat((hex >> 16) & 255)/255, green: CGFloat((hex >> 8) & 255)/255, blue: CGFloat(hex & 255)/255, alpha: 1) }
    var base: Color { Color(nsColor: Self.ns(baseHex)) }
    var surface: Color { Color(nsColor: Self.ns(surfaceHex)) }
    var text: Color { Color(nsColor: Self.ns(textHex)) }
    var muted: Color { Color(nsColor: Self.ns(mutedHex)) }
    var accent: Color { Color(nsColor: Self.ns(accentHex)) }
    static let all: [AppTheme] = [
'''
for t in themes:
    swift+='        AppTheme(id: "'+t['id']+'", name: "'+t['name']+'", dark: '+str(t['dark']).lower()+', '+', '.join(r+'Hex: 0x'+t[r] for r in roles[:5])+'),\n'
swift+='    ]\n    static func find(_ id: String) -> AppTheme { all.first { $0.id == id } ?? all[3] }\n}\n'
(ROOT/'clients/macos/Themes.swift').write_text(swift)
c='/* Generated by scripts/generate-themes.py. */\n#ifndef BS_THEMES_H\n#define BS_THEMES_H\n'
c+='typedef struct { const char *id, *name; unsigned long base,surface,text,muted,accent,shine,shadow; } BSTheme;\n'
c+='#define BS_THEME_COUNT '+str(len(themes))+'\n#define BS_THEME_DEFAULT 3\n#define BS_THEME_CLASSIC 7\nstatic const BSTheme bs_themes[BS_THEME_COUNT] = {\n'
for t in themes:c+='    {"'+t['id']+'","'+t['name']+'",'+','.join('0x'+t[r]+'UL' for r in roles)+'},\n'
c+='};\n#endif\n'; (ROOT/'clients/amiga/themes.h').write_text(c)
print('Generated shared client palettes')
win='/* Generated from assets/themes/palettes.json. */\n#ifndef BITSKIM_WINDOWS_THEMES_H\n#define BITSKIM_WINDOWS_THEMES_H\n'
win+='typedef struct { const char *id; const wchar_t *name; COLORREF base,surface,text,muted,accent; int dark; } WinTheme;\n#define WIN_THEME_COUNT 8\n#define WIN_THEME_DEFAULT 3\nstatic const WinTheme win_themes[WIN_THEME_COUNT] = {\n'
for t in themes:
    colors=[]
    for role in roles[:5]:
        value=t[role]; colors.append('RGB(0x'+value[:2]+',0x'+value[2:4]+',0x'+value[4:]+')')
    win+='    {"'+t['id']+'",L"'+t['name']+'",'+','.join(colors)+','+str(int(t['dark']))+'},\n'
win+='};\n#endif\n'
(ROOT/'clients/windows/themes.h').write_text(win)

ios = swift.replace('import AppKit', 'import UIKit').replace('struct AppTheme', 'struct MobileTheme').replace('AppTheme', 'MobileTheme').replace('NSColor', 'UIColor').replace('static func ns', 'static func ui').replace('UIColor(srgbRed:', 'UIColor(red:').replace('Color(nsColor: Self.ns(', 'Color(uiColor: Self.ui(')
(ROOT/'clients/ios/App/Themes.swift').write_text(ios)
